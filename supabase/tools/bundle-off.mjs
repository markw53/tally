/* Produces a single-file version of the off function for people deploying
   through the Supabase dashboard rather than the CLI, where pasting one file
   into a browser editor is the whole interface.

     node supabase/tools/bundle-off.mjs          # write dashboard/off.ts
     node supabase/tools/bundle-off.mjs --check  # fail if it's out of date

   The --check mode runs in the test suite, so the pasted-in copy can't
   silently drift from the real source. */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fn = join(here, "../functions/off");
const out = join(here, "../dashboard/off.ts");

const food = readFileSync(join(fn, "food.ts"), "utf8");
const index = readFileSync(join(fn, "index.ts"), "utf8");

const IMPORT = /^import \{[^}]*\} from "\.\/food\.ts";\n/m;
if (!IMPORT.test(index)) {
  console.error("bundle-off: index.ts no longer imports ./food.ts — update this script.");
  process.exit(2);
}

/* Drop food.ts's own header comment (it explains the split, which doesn't
   apply once inlined) and un-export, since there's nothing to export to. */
const inlined = food
  .replace(/^\/\/[^\n]*\n(?:\/\/[^\n]*\n)*\n/, "")
  .replace(/^export (type|function) /gm, "$1 ");

const banner = `// ===========================================================================
// GENERATED — do not edit this file.
//
// This is supabase/functions/off/index.ts and food.ts inlined into one file,
// for deploying through the Supabase dashboard's editor. Edit the originals
// and re-run:  node supabase/tools/bundle-off.mjs
// ===========================================================================

`;

const bundled = banner + index.replace(IMPORT, "") .replace(
  /\/\* ------------------------------------------------------------ rate limit ---/,
  inlined.trimEnd() + "\n\n/* ------------------------------------------------------------ rate limit ---",
);

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch { /* not generated yet */ }
  if (current !== bundled) {
    console.error("✗ supabase/dashboard/off.ts is out of date — run: node supabase/tools/bundle-off.mjs");
    process.exit(1);
  }
  console.log("  ✓ the dashboard copy matches the source");
  process.exit(0);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, bundled);
console.log(`wrote ${out} (${(bundled.length / 1024).toFixed(1)} KB)`);
